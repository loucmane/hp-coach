#!/usr/bin/env -S node --experimental-strip-types
// Public manifest: IDs only. Questions and explanations remain gated.
// Node 22: run with --experimental-strip-types to read the shared figure exclusions.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = 'app/src/data/workedExamples.generated.ts'
const SECTIONS = new Set(['NOG', 'KVA', 'XYZ', 'MEK'])
const readJson = (file) => JSON.parse(readFileSync(path.join(ROOT, file), 'utf8'))

// Preserve entry and example order for selection; sort only the final IDs.
export function buildWorkedExamples(frameworks, bank, explanations, excluded = new Set()) {
  const withoutFigures = new Set(bank.filter(q => !q.figure).map(q => q.qid))
  // Match the framework drill picker; missing, incomplete and excluded questions
  // cannot keep a drill alive. Deduplicate repeated IDs in an entry.
  const drillable = new Set(bank.filter(q =>
    q.parsing_status === 'complete' && q.options && !excluded.has(q.qid)
  ).map(q => q.qid))
  const poolsByEntry = new Map(frameworks.flatMap(framework => (framework.entries ?? []).map(entry =>
    [entry, new Set((entry.example_questions ?? []).filter(id => drillable.has(id)))]
  )))
  const pools = [...poolsByEntry.values()]
  const taken = new Set()
  const entries = new Set()
  const examples = []
  for (const framework of frameworks) {
    if (!SECTIONS.has(framework.section)) continue
    for (const entry of framework.entries) {
      if (entries.has(entry.id)) continue
      if (!poolsByEntry.get(entry)?.size) continue
      const qid = (entry.example_questions ?? []).find(id => {
        const explanation = explanations[id]
        return withoutFigures.has(id) && !taken.has(id) && explanation?.framework_id === entry.id &&
          explanation.steps?.filter(step => step.tier === 'essential').length >= 3 &&
          // A shared qid can also be the last remaining drill for another entry.
          pools.every(pool => !pool.has(id) || pool.size > 1)
      })
      if (!qid) continue
      taken.add(qid)
      for (const pool of pools) pool.delete(qid)
      entries.add(entry.id)
      examples.push({ entryId: entry.id, section: framework.section, qid })
    }
  }
  return examples.sort((a, b) => a.entryId < b.entryId ? -1 : a.entryId > b.entryId ? 1 : 0)
}

async function main() {
  const { EXCLUDED_QUESTIONS } = await import('../app/src/data/figureOverrides.ts')
  const frameworks = readdirSync(path.join(ROOT, 'frameworks')).sort()
    .filter(file => file.endsWith('.json'))
    .map(file => readJson(`frameworks/${file}`))
  const index = readJson('app/public/data/_index.json')
  const bank = index.exams.flatMap(({ exam_id }) => readJson(`app/public/data/${exam_id}.json`))
  const explanations = Object.assign({}, ...readdirSync(path.join(ROOT, 'data/explanations'))
    .sort().filter(file => file.endsWith('.json'))
    .map(file => readJson(`data/explanations/${file}`)))
  const examples = buildWorkedExamples(frameworks, bank, explanations, EXCLUDED_QUESTIONS)
  const rows = examples.map(({ entryId, section, qid }) =>
    `  { entryId: '${entryId}', section: '${section}', qid: '${qid}' },`).join('\n')
  const text = `// Generated by node --experimental-strip-types scripts/build_worked_examples.mjs. IDs only; do not edit.
import type { Section } from './questions'

export const WORKED_EXAMPLES: readonly { entryId: string; section: Section; qid: string }[] = [
${rows}
]

export const WORKED_EXAMPLE_QIDS: ReadonlySet<string> = new Set(WORKED_EXAMPLES.map((x) => x.qid))
`
  if (process.argv.includes('--check')) {
    let current = null
    try { current = readFileSync(path.join(ROOT, OUTPUT), 'utf8') } catch { /* absent = stale */ }
    if (current !== text) {
      console.error(`build_worked_examples: ${OUTPUT} is stale; re-run without --check`)
      process.exitCode = 1
      return
    }
    console.log(`build_worked_examples: up to date (${examples.length} examples)`)
  } else {
    writeFileSync(path.join(ROOT, OUTPUT), text)
    console.log(`build_worked_examples: wrote ${examples.length} examples`)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
