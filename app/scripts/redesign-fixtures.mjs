#!/usr/bin/env node
// Copies the real content the redesign kit's round-2 fixtures show into
// app/src/components/devbake/redesign/r2Fixtures.ts (kit v2, bead hpf-qr0p.7;
// docs/redesign/kit-v2.md), verbatim and in a fixed order:
//
//   - Höstprovet 2025, kvant1: all 40 questions in printed order, from
//     app/public/data/host-2025.json, with the DTK figure pages patched in
//     from app/public/figures/dtk/_index.json and the suppressed figures of
//     app/src/data/figureOverrides.ts dropped — what data/questions.ts
//     loadBank serves — and, served the same way, the Kvantfråga screen's
//     three questions (XYZ with math from kvant2, KVA and NOG from kvant1)
//   - the explanations of those three and of the DTK screen's question,
//     from app/public/explanations/host-2025.json, without the generator's
//     `_meta` provenance block
//   - the ELF P5 unit elf-b19-003 from the committed sample export
//     pipeline/synthetic/infold/preview/sample/p5-bank-sample.json, with its
//     reviewed explanation from data/explanations/p5-pilot.json
//   - the prompts of the repetition pile's other questions (Våren 2026)
//   - each framework catalog's index (id, headword, kicker, number of
//     example questions) and the open lesson's entry, from
//     app/public/frameworks/*.json
//   - the normering tables of the two sittings the Provpass screens score
//     (app/public/normering/*.json) and the number of fully parsed
//     questions in each listed pass
//
// Only the block between the BEGIN/END GENERATED markers is rewritten; the
// whole file is then formatted with the app's Biome, so the output is
// deterministic. `--check` compares instead of writing and exits 1 on drift.
// r2Fixtures.test.ts pins the same content to the same sources.
//
// Usage, from app/:  node scripts/redesign-fixtures.mjs [--check]

import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const APP = path.resolve(HERE, '..')
const REPO = path.resolve(APP, '..')
const TARGET = 'src/components/devbake/redesign/r2Fixtures.ts'
const BEGIN = '// ── BEGIN GENERATED by app/scripts/redesign-fixtures.mjs: do not edit by hand ──'
const END = '// ── END GENERATED ──'

// ── What the fixtures copy ───────────────────────────────────────────

const PASS = { examId: 'host-2025', provpass: 'kvant1' }
/** The Kvantfråga screen's three questions, in order: XYZ (math), KVA, NOG. */
const QUANT_QIDS = ['host-2025-kvant2-XYZ-009', 'host-2025-kvant1-KVA-017', 'host-2025-kvant1-NOG-025']
const DTK_QID = 'host-2025-kvant1-DTK-029'
const ELF_UNIT_ID = 'elf-b19-003'
const OPEN_LESSON_ID = 'LAS-TYPE-003'
/** The rest of the repetition pile: questions met in earlier sittings. */
const PILE_QIDS = [
  'var-2026-verb1-ORD-004',
  'var-2026-verb1-ORD-009',
  'var-2026-verb1-MEK-023',
  'var-2026-verb1-MEK-027',
  'var-2026-verb2-ORD-002',
  'var-2026-verb2-MEK-025',
  'var-2026-kvant1-XYZ-003',
  'var-2026-kvant1-XYZ-009',
  'var-2026-kvant1-KVA-015',
  'var-2026-kvant1-NOG-024',
  'var-2026-kvant2-XYZ-005',
  'var-2026-kvant2-KVA-019',
  'var-2026-kvant2-NOG-026',
  'var-2026-kvant2-DTK-031',
  'var-2026-kvant2-DTK-033',
]
/** The authentic passes the Provpass hub lists. */
const LISTED_PASSES = [
  'var-2026:kvant1',
  'var-2026:kvant2',
  'host-2025:kvant1',
  'host-2025:kvant2',
  'var-2026:verb1',
  'var-2026:verb2',
  'host-2025:verb1',
  'host-2025:verb2',
]
const NORMERING_SITTINGS = ['host-2025', 'var-2026']
/** Exam order — the catalogs' order in Uppslag. */
const CATALOGS = [
  ['ORD', 'ord_roots.json'],
  ['LÄS', 'las_taxonomy.json'],
  ['MEK', 'mek_protocol.json'],
  ['ELF', 'elf_taxonomy.json'],
  ['XYZ', 'xyz_traps.json'],
  ['KVA', 'kva_traps.json'],
  ['NOG', 'nog_traps.json'],
  ['DTK', 'dtk_tactics.json'],
]

// ── Sources ──────────────────────────────────────────────────────────

const readText = (rel) => readFileSync(path.join(REPO, rel), 'utf8')
const readJson = (rel) => JSON.parse(readText(rel))

function fail(message) {
  console.error(`redesign-fixtures: ${message}`)
  process.exit(2)
}

/** The qids of figureOverrides.ts SUPPRESSED_FIGURES. */
function suppressedFigures() {
  const src = readText('app/src/data/figureOverrides.ts')
  const block = /SUPPRESSED_FIGURES[^=]*=\s*new Set\(\[([\s\S]*?)\]\)/.exec(src)
  if (!block) fail('SUPPRESSED_FIGURES not found in figureOverrides.ts')
  return new Set([...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1]))
}

const banks = new Map()
function bank(examId) {
  if (!banks.has(examId)) banks.set(examId, readJson(`app/public/data/${examId}.json`))
  return banks.get(examId)
}

const complete = (q) => q.parsing_status === 'complete' && q.options

/** data/frameworks.ts entryHeadword, per family. */
function headword(entry, family) {
  switch (family) {
    case 'ord_roots':
      return entry.root
    case 'dtk_tactics':
      return entry.tactic
    case 'mek_protocol':
      return entry.constraint_type
    case 'las_taxonomy':
    case 'elf_taxonomy':
      return entry.question_type
    default:
      return entry.pattern_description
  }
}

function withoutMeta(explanation, qid) {
  if (!explanation) fail(`no explanation for ${qid}`)
  const { _meta, ...rest } = explanation
  return rest
}

// Questions as loadBank serves them.
const dtkIndex = readJson('app/public/figures/dtk/_index.json')
const suppressed = suppressedFigures()
function served(q) {
  const row = { ...q }
  const page = dtkIndex[q.qid]
  if (page) {
    row.figure = {
      src: `figures/dtk/${page.figure}`,
      aspect_ratio: page.width / page.height,
      kind: 'raster',
    }
  }
  if (suppressed.has(q.qid)) row.figure = null
  return row
}
const passQuestions = bank(PASS.examId)
  .filter((q) => q.exam_id === PASS.examId && q.provpass === PASS.provpass && complete(q))
  .sort((a, z) => a.number - z.number)
  .map(served)
if (passQuestions.length !== 40) fail(`expected 40 questions in ${PASS.examId} ${PASS.provpass}`)
if (!passQuestions.some((q) => q.qid === DTK_QID)) fail(`${DTK_QID} is not in the pass`)
const quantQuestions = QUANT_QIDS.map((qid) => {
  const q = bank(PASS.examId).find((x) => x.qid === qid)
  if (!q || !complete(q)) fail(`${qid} is not a complete question`)
  return served(q)
})
const dtkPages = Object.fromEntries(
  passQuestions.filter((q) => dtkIndex[q.qid]).map((q) => [q.qid, dtkIndex[q.qid]]),
)

const hostExplanations = readJson(`app/public/explanations/${PASS.examId}.json`)
const quantExplanations = Object.fromEntries(
  [...QUANT_QIDS, DTK_QID].map((qid) => [qid, withoutMeta(hostExplanations[qid], qid)]),
)

const sample = readJson('pipeline/synthetic/infold/preview/sample/p5-bank-sample.json')
const elfRows = sample.questions
  .filter((r) => r.unit_id === ELF_UNIT_ID)
  .sort((a, z) => a.number - z.number)
if (elfRows.length === 0) fail(`unit ${ELF_UNIT_ID} not in the sample export`)
const elfUnit = {
  unitId: ELF_UNIT_ID,
  revision: elfRows[0].revision,
  section: elfRows[0].section,
  title: elfRows[0].title,
  context: elfRows[0].context,
  questions: elfRows.map((r) => ({
    qid: r.qid,
    number: r.number,
    prompt: r.prompt,
    options: r.options,
    answer: r.answer,
  })),
}
const pilot = readJson('data/explanations/p5-pilot.json')
const elfExplanations = Object.fromEntries(
  elfRows.map((r) => {
    if (!pilot[r.qid]) fail(`no pilot explanation for ${r.qid}`)
    return [r.qid, pilot[r.qid]]
  }),
)

const pilePrompts = Object.fromEntries(
  PILE_QIDS.map((qid) => {
    const examId = qid.slice(0, qid.search(/-(verb|kvant)[12]-/))
    const q = bank(examId).find((x) => x.qid === qid)
    if (!q || !complete(q)) fail(`${qid} is not a complete question`)
    return [qid, q.prompt]
  }),
)

const passSizes = Object.fromEntries(
  LISTED_PASSES.map((id) => {
    const [examId, provpass] = id.split(':')
    const n = bank(examId).filter((q) => q.provpass === provpass && complete(q)).length
    if (n === 0) fail(`no questions in ${id}`)
    return [id, n]
  }),
)

const normering = Object.fromEntries(
  NORMERING_SITTINGS.map((id) => [id, readJson(`app/public/normering/${id}.json`)]),
)

let openLesson = null
const frameworkIndex = CATALOGS.map(([section, file]) => {
  const catalog = readJson(`app/public/frameworks/${file}`)
  if (catalog.section !== section) fail(`${file} is not the ${section} catalog`)
  const hit = catalog.entries.find((e) => e.id === OPEN_LESSON_ID)
  if (hit) openLesson = hit
  return {
    section,
    family: catalog.family,
    entries: catalog.entries.map((e) => {
      const out = { id: e.id, headword: headword(e, catalog.family) }
      if (e.tldr) out.kicker = e.tldr
      out.examples = e.example_questions.length
      return out
    }),
  }
})
if (!openLesson) fail(`${OPEN_LESSON_ID} not found in the catalogs`)

// ── Emit ─────────────────────────────────────────────────────────────

/** A JSON literal with private-use characters (the U+E000/U+E001 math and
 *  NOG markers) as \u escapes, so no editor can strip them. */
// The private-use block, U+E000–U+F8FF, built from its codes so no editor
// can strip the characters from this file.
const PRIVATE_USE = new RegExp(
  `[${String.fromCharCode(0xe000)}-${String.fromCharCode(0xf8ff)}]`,
  'g',
)

function literal(value) {
  return JSON.stringify(value, null, 2).replace(
    PRIVATE_USE,
    (ch) => `\\u${ch.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')}`,
  )
}

const blocks = [
  [
    'PASS_QUESTIONS',
    'Question[]',
    passQuestions,
    'Höstprovet 2025, kvant1: the pass the running Provpass and its result show, in printed order. The DTK screen opens on one of its questions.',
  ],
  [
    'QUANT_QUESTIONS',
    'Question[]',
    quantQuestions,
    'The Kvantfråga screen’s questions, in order: XYZ with math (kvant2), KVA and NOG (kvant1).',
  ],
  ['DTK_PAGES', 'Record<string, DtkPage>', dtkPages, 'The pass’s DTK figure pages, intrinsic size.'],
  [
    'QUANT_EXPLANATIONS',
    'Record<string, Explanation>',
    quantExplanations,
    'The reviewed explanations of the Kvantfråga questions and the DTK question.',
  ],
  ['ELF_UNIT', 'P5Unit', elfUnit, 'The ELF screen’s unit: a P5 practice text.'],
  ['ELF_EXPLANATIONS', 'Record<string, Explanation>', elfExplanations, 'Its reviewed explanation.'],
  [
    'PILE_PROMPTS',
    'Record<string, string>',
    pilePrompts,
    'Prompts of the repetition pile’s other questions.',
  ],
  [
    'PASS_SIZES',
    'Record<string, number>',
    passSizes,
    'Fully parsed questions per listed pass (`examId:provpass`).',
  ],
  ['NORMERING', 'Record<string, NormeringSitting>', normering, 'The normering of the scored sittings.'],
  [
    'FRAMEWORK_INDEX',
    'FrameworkIndexSection[]',
    frameworkIndex,
    'Every framework catalog’s index, in exam order.',
  ],
  ['OPEN_LESSON', 'ProtocolEntry', openLesson, 'The lesson open in Uppslag, verbatim.'],
]

const generated = blocks
  .map(([name, type, value, doc]) => `/** ${doc} */\nexport const ${name}: ${type} = ${literal(value)}\n`)
  .join('\n')

const file = path.join(APP, TARGET)
const current = readFileSync(file, 'utf8')
const from = current.indexOf(BEGIN)
const to = current.indexOf(END)
if (from === -1 || to === -1 || to < from) fail(`${TARGET} has no BEGIN/END GENERATED markers`)
const spliced = `${current.slice(0, from)}${BEGIN}\n${generated}${current.slice(to)}`

const biome = spawnSync(
  path.join(APP, 'node_modules', '.bin', 'biome'),
  ['format', `--stdin-file-path=${TARGET}`],
  { cwd: APP, input: spliced, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
)
if (biome.status !== 0) fail(`biome format failed:\n${biome.stderr}`)
const formatted = biome.stdout

if (process.argv.includes('--check')) {
  if (formatted !== current) {
    console.error(`redesign-fixtures: ${TARGET} is out of date; run node scripts/redesign-fixtures.mjs`)
    process.exit(1)
  }
  console.log(`redesign-fixtures: ${TARGET} is up to date`)
} else if (formatted === current) {
  console.log(`redesign-fixtures: ${TARGET} already up to date`)
} else {
  writeFileSync(file, formatted)
  console.log(`redesign-fixtures: wrote ${TARGET}`)
}
